-- QMRS MODULE 1 - ORACLE DATABASE DEFINITION
CREATE TABLE SITE_SETTINGS (
    SETTING_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    SETTING_NAME VARCHAR2(100 CHAR) NOT NULL,
    SETTING_VALUE VARCHAR2(1000 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(500 CHAR),
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SITE_SETTINGS PRIMARY KEY (SETTING_ID),
    CONSTRAINT UK_SITE_SETTINGS_NAME UNIQUE (SETTING_NAME)
);

CREATE TABLE PRICING_PLANS (
    PLAN_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PLAN_CODE VARCHAR2(50 CHAR) NOT NULL,
    PLAN_NAME VARCHAR2(100 CHAR) NOT NULL,
    USER_TYPE VARCHAR2(30 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(500 CHAR),
    PRICE NUMBER(12,2) DEFAULT 0 NOT NULL,
    CURRENCY_CODE VARCHAR2(10 CHAR) NOT NULL,
    BILLING_PERIOD VARCHAR2(20 CHAR) NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    DISPLAY_ORDER NUMBER(5) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PRICING_PLANS PRIMARY KEY (PLAN_ID),
    CONSTRAINT UK_PRICING_PLANS_CODE UNIQUE (PLAN_CODE),
    CONSTRAINT CK_PRICING_PLANS_PRICE CHECK (PRICE >= 0),
    CONSTRAINT CK_PRICING_PLANS_ACTIVE CHECK (IS_ACTIVE IN (0,1))
);

CREATE TABLE USERS (
    USER_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PUBLIC_UUID VARCHAR2(36 CHAR) NOT NULL,
    FULL_NAME VARCHAR2(150 CHAR) NOT NULL,
    EMAIL VARCHAR2(254 CHAR),
    COUNTRY_CODE VARCHAR2(10 CHAR),
    MOBILE_NUMBER VARCHAR2(20 CHAR),
    PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
    USER_TYPE VARCHAR2(20 CHAR) NOT NULL,
    ACCOUNT_STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    EMAIL_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL,
    MOBILE_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL,
    TERMS_VERSION VARCHAR2(30 CHAR) NOT NULL,
    PRIVACY_VERSION VARCHAR2(30 CHAR) NOT NULL,
    TERMS_ACCEPTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UK_USERS_PUBLIC_UUID UNIQUE (PUBLIC_UUID),
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_USERS_MOBILE UNIQUE (COUNTRY_CODE, MOBILE_NUMBER),
    CONSTRAINT CK_USERS_TYPE CHECK (USER_TYPE IN ('CANDIDATE','EMPLOYER')),
    CONSTRAINT CK_USERS_STATUS CHECK (ACCOUNT_STATUS IN ('PENDING','ACTIVE','SUSPENDED','BLOCKED','DEACTIVATED')),
    CONSTRAINT CK_USERS_EMAIL_VERIFIED CHECK (EMAIL_VERIFIED IN (0,1)),
    CONSTRAINT CK_USERS_MOBILE_VERIFIED CHECK (MOBILE_VERIFIED IN (0,1)),
    CONSTRAINT CK_USERS_CONTACT CHECK (EMAIL IS NOT NULL OR MOBILE_NUMBER IS NOT NULL)
);

CREATE TABLE USER_OTP_VERIFICATION (
    OTP_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER(19) NOT NULL,
    OTP_CODE_HASH VARCHAR2(255 CHAR) NOT NULL,
    OTP_TYPE VARCHAR2(20 CHAR) NOT NULL,
    SENT_TO VARCHAR2(254 CHAR) NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    VERIFIED_AT TIMESTAMP,
    ATTEMPT_COUNT NUMBER(3) DEFAULT 0 NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USER_OTP PRIMARY KEY (OTP_ID),
    CONSTRAINT FK_USER_OTP_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT CK_USER_OTP_TYPE CHECK (OTP_TYPE IN ('EMAIL','MOBILE')),
    CONSTRAINT CK_USER_OTP_STATUS CHECK (STATUS IN ('PENDING','VERIFIED','EXPIRED','BLOCKED')),
    CONSTRAINT CK_USER_OTP_ATTEMPTS CHECK (ATTEMPT_COUNT BETWEEN 0 AND 999)
);

CREATE INDEX IDX_USERS_STATUS ON USERS(ACCOUNT_STATUS);
CREATE INDEX IDX_USERS_TYPE_STATUS ON USERS(USER_TYPE, ACCOUNT_STATUS);
CREATE INDEX IDX_USERS_EMAIL_LOWER ON USERS(LOWER(EMAIL));
CREATE INDEX IDX_USERS_MOBILE_LOOKUP ON USERS(MOBILE_NUMBER);
CREATE INDEX IDX_USER_OTP_USER ON USER_OTP_VERIFICATION(USER_ID);
CREATE INDEX IDX_USER_OTP_ACTIVE ON USER_OTP_VERIFICATION(USER_ID, OTP_TYPE, STATUS, EXPIRES_AT);

